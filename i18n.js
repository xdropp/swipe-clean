  const LANGS = { 'pt-BR': 'Português (Brasil)', en: 'English' };

  // "pt", "pt-BR", "pt-PT" → pt-BR; qualquer outro idioma → en
  function resolve(pref) {
    return String(pref || '').toLowerCase().startsWith('pt') ? 'pt-BR' : 'en';
  }

  function createT(lang) {
    const dict = STRINGS[lang] || STRINGS.en;
    return function t(key, params) {
      let s = dict[key];
      if (s === undefined) s = STRINGS.en[key];
      if (s === undefined) return key;
      if (typeof s === 'object') s = params && Number(params.n) === 1 ? s.one : s.other;
      if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m));
      return s;
    };
  }

  const locale = (lang) => (lang === 'pt-BR' ? 'pt-BR' : 'en-US');

  return { STRINGS, LANGS, resolve, createT, locale };
